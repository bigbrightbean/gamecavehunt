function triggerFireChaos(){

  gameUnlocked = false

  flashScreen()

  setTimeout(()=>{

    const available = grid.filter(t => !t.classList.contains("revealed"))

    if(available.length === 0){
      gameUnlocked = true
      return
    }

    let steps = 12
    let delay = 60

    let currentTile = null

    function jump(){

      /* 🧹 remove previous highlight */
      if(currentTile){
        currentTile.classList.remove("chaos-highlight")
      }

      /* 🎯 pick new tile */
      currentTile = available[Math.floor(Math.random()*available.length)]

      currentTile.classList.add("chaos-highlight")

      steps--

      if(steps <= 0){

        const finalTile = currentTile

        setTimeout(()=>{

          /* 🧹 remove highlight */
          finalTile.classList.remove("chaos-highlight")

          /* 💥 IMPACT EFFECT */
          finalTile.classList.add("chaos-final")

          setTimeout(()=>{

            finalTile.classList.remove("chaos-final")

            /* ===================================================== */
            /* 🎯 SMART FIRE (COMEBACK LOGIC) */
            /* ===================================================== */

            let forced = finalTile.dataset.animal

            if(forced === "🔥" || forced === "🎁"){

              const isDogTurn = currentTeam === "dog"

              const losing = isDogTurn
                ? dogScore < tigerScore
                : tigerScore < dogScore

              let diamondChance = losing ? 0.5 : 0.25

              forced = Math.random() < diamondChance ? "💎" : "🪨"

              finalTile.dataset.animal = forced
            }

            /* ===================================================== */
            /* 🎴 VISUAL REVEAL TILE (NO openTile) */
            /* ===================================================== */

            finalTile.classList.add("revealed")
            finalTile.style.opacity = "0.4"
            finalTile.style.pointerEvents = "none"
            finalTile.innerText = forced

            /* ===================================================== */
            /* 🪟 SHOW RESULT POPUP AGAIN */
            /* ===================================================== */

            const idx = grid.indexOf(finalTile)
            showResult(forced, idx, true)   // 🔥 fromFire = true

          },200)

        }, delay)

        return
      }

      /* ⏱ slow down */
      delay += 25

      setTimeout(jump, delay)
    }

    jump()

  },200)
}

