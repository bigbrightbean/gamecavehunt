function explodeNeighbors(centerIndex){

  const cols = getComputedStyle(forestGrid)
    .gridTemplateColumns.split(" ").length

  const leftIndex = centerIndex - 1
  const rightIndex = centerIndex + 1

  let affected = [centerIndex]

  /* 🧠 SAME ROW CHECK */
  if(centerIndex % cols !== 0){
    affected.push(leftIndex)
  }

  if(centerIndex % cols !== cols - 1){
    affected.push(rightIndex)
  }

  affected.forEach(i=>{

    const tile = grid[i]
    if(!tile) return   // ✅ prevent crash

    tile.classList.add("revealed")

    /* 💥 EXPLOSION EFFECT */
    tile.classList.add("explode")
    setTimeout(()=>tile.classList.remove("explode"), 300)

    tile.style.opacity = "0.4"
    tile.style.pointerEvents = "none"

    /* 🔥 FORCE DIAMOND (except center) */
    if(i !== centerIndex){
      tile.dataset.animal = "💎"
    }

    tile.innerText = tile.dataset.animal
  })
}

