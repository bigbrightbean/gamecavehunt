    decoEl.style.animationDelay = (Math.random() * 3.5) + "s"

    /* 🎯 RANDOM SPEED */
    decoEl.style.animationDuration = (Math.random() * 1.5 + 2.5) + "s"

    /* 🎯 RANDOM HEIGHT VARIATION (FLOAT DISTANCE) */
    const floatY = Math.random() * 6 + 6   // 6px → 12px
    decoEl.style.setProperty("--floatY", floatY + "px")

    tile.appendChild(decoEl)

    /* ===================== */
    /* 🎯 STORE ITEM */
    /* ===================== */

    tile.dataset.animal = pool[i]

    /* ===================== */
    /* 🖱 CLICK */
    /* ===================== */

    tile.onclick = ()=> selectTile(tile)

    /* ===================== */
    /* 📦 ADD TO GRID */
    /* ===================== */

