function openTile(tile){

  /* 🔒 BLOCK IF GAME LOCKED */
  if(!gameUnlocked) return

  const index = grid.indexOf(tile)

  /* ============================== */
  /* ⛏️ DIG PROGRESS SYSTEM */
  /* ============================== */

  if(!digProgress[index]){
    digProgress[index] = 0
  }

  digProgress[index]++

  /* ============================== */
  /* 💥 HIT FEEDBACK */
  /* ============================== */

  tile.classList.add("dig-hit")

  setTimeout(()=>{
    tile.classList.remove("dig-hit")
  },120)

  /* ============================== */
  /* 🪨 CRACK STAGES */
  /* ============================== */

  if(digProgress[index] === 1){
    tile.classList.add("crack1")
  }

  if(digProgress[index] === 2){
    tile.classList.add("crack2")
  }

  /* ⛔ NOT FULLY DUG YET */
  if(digProgress[index] < 3){
    return
  }

  /* ===================================================== */
  /* 🎯 TURN COUNT (ONLY COUNT FULL DIGS) */
  /* ===================================================== */

  turnCount++

  /* ============================== */
  /* 💥 FINAL BREAK */
  /* ============================== */

  tile.classList.add("break-open")

  spawnRockParticles(tile)

  /* 🔒 LOCK GAME DURING RESULT */
  gameUnlocked = false

  /* 🧹 REMOVE OPEN BUTTON */
  const oldBtn = document.querySelector(".openBtn")
  if(oldBtn) oldBtn.remove()

  /* 🎯 MARK TILE */
  tile.classList.add("revealed")

  tile.style.opacity = "0.4"
  tile.style.pointerEvents = "none"

  /* ============================== */
  /* 🎯 GET TILE RESULT */
  /* ============================== */

  let animal = tile.dataset.animal

  /* ===================================================== */
  /* 🚫 EARLY GAME PROTECTION (FIRST 4 TURNS) */
  /* ===================================================== */

  if(turnCount <= 4){

    if(animal === "🔥" || animal === "🎁"){

      animal = Math.random() < 0.4 ? "💎" : "🪨"
      tile.dataset.animal = animal

    }
  }

  /* ===================================================== */
  /* 🎯 GUARANTEE FIRE + GIFT (LATE GAME FORCE) */
  /* ===================================================== */

  if(turnCount > 15){

    /* 🔥 force fire if never appeared */
    if(!fireTriggered && animal === "🪨"){
      animal = "🔥"
      tile.dataset.animal = animal
    }

    /* 🎁 force gift if never appeared */
    else if(!giftTriggered && animal === "🪨"){
      animal = "🎁"
      tile.dataset.animal = animal
    }

  }

  /* ============================== */
  /* 🎁 SAFE MODE */
  /* ============================== */

  if(forceSafeNextPick){

    if(animal === "🔥" || animal === "🎁"){
      animal = "🪨"
      tile.dataset.animal = animal
    }

    forceSafeNextPick = false
  }

  /* ============================== */
  /* 🧱 SHOW RESULT */
  /* ============================== */

  tile.innerText = animal

  /* 🧹 CLEAR GIFT MODE */
  clearGiftMode()

  /* 🪟 SHOW RESULT */
  showResult(animal, index)

  /* 🧹 RESET DIG STATE */
  delete digProgress[index]
}


